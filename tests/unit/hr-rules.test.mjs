import assert from "node:assert/strict";
import { reminderStage, reminderDue, maskNumber, mayOpenHr, expiryWords, expiryTone, hrFileName } from "../../src/lib/hr-rules.ts";

const today = "2026-11-11";
assert.equal(reminderStage("passport", "2027-01-05", today), 60);
assert.equal(reminderStage("passport", "2027-02-05", today), null);
assert.equal(reminderStage("emirates_id", "2026-12-25", today), null);
assert.equal(reminderStage("emirates_id", "2026-12-05", today), 30);
assert.equal(reminderStage("visa", "2026-11-20", today), 14);
assert.equal(reminderStage("visa", "2026-11-15", today), 7);
assert.equal(reminderStage("visa", "2026-11-11", today), 0);
assert.equal(reminderStage("visa", "2026-10-01", today), 0);
assert.equal(reminderStage("photo", "2026-10-01", today), null);
assert.equal(reminderStage("visa", null, today), null);
assert.ok(reminderDue(60, null));
assert.ok(!reminderDue(60, 60));
assert.ok(reminderDue(14, 60));
assert.ok(reminderDue(0, 7));
assert.ok(!reminderDue(null, null));
assert.equal(maskNumber("784-1990-1234567-1"), "•••-••••-••••••7-1");
assert.ok(maskNumber("784-1990-1234567-1").endsWith("7-1") && !maskNumber("784-1990-1234567-1").includes("1990"));
assert.equal(maskNumber(""), "");
assert.ok(mayOpenHr({ role_id: "owner" }));
assert.ok(mayOpenHr({ role_id: "accounts", is_head_accountant: true }));
assert.ok(!mayOpenHr({ role_id: "accounts", is_head_accountant: false }));
assert.ok(!mayOpenHr({ role_id: "service_advisor", is_head_accountant: true }));
assert.equal(expiryWords("2026-11-10", today), "Expired 1 day ago");
assert.equal(expiryTone("visa", "2026-11-10", today), "red");
assert.equal(expiryTone("visa", "2026-12-20", today), "amber");
assert.equal(hrFileName("Emirates ID", "Mohammed Ali", "scan.JPG", "image/jpeg"), "EMIRATES ID - MOHAMMED ALI.jpg");
console.log("hr-rules: ok");
