/** The owner issues a credit note against an invoice: an amount before VAT with a description. The invoice itself stays locked. */
export async function issueCreditNote(invoiceId: string, formData: FormData) {
  const staff = await requirePermission("approveCreditNotes");
  const back = `/invoices/${invoiceId}`;
  const bundle = await loadInvoice(invoiceId);
  if (!bundle || bundle.invoice.kind !== "tax_invoice") redirect("/invoices");
  const amount = Number(String(formData.get("amount") ?? "").replace(/[^\d.]/g, ""));
  const description = blankToNull(formData.get("description"));
  if (!Number.isFinite(amount) || amount <= 0) redirect(`${back}?error=${encodeURIComponent("Enter the amount before VAT to credit.")}`);
  if (!description) redirect(`${back}?error=${encodeURIComponent("Describe the correction.")}`);
  const credited = bundle.creditNotes.filter((c) => c.status === "issued").reduce((a, c) => a + c.taxable_aed, 0);
  if (amount + credited > bundle.invoice.taxable_aed + 0.005) redirect(`${back}?error=${encodeURIComponent("That is more than the invoice.")}`);
  const settings = await getSettings();
  const vatPct = bundle.invoice.taxable_aed ? round2((bundle.invoice.vat_aed / bundle.invoice.taxable_aed) * 100) || 5 : 5;
  const vat = round2(amount * (vatPct / 100));
  const number = await nextDocumentNumber("credit_note", settings);
  const admin = createAdminClient();
  const { data: cn, error } = await admin.from("invoices").insert({ number, kind: "credit_note", job_id: bundle.invoice.job_id, customer_id: bundle.invoice.customer_id, vehicle_id: bundle.invoice.vehicle_id, credit_of: invoiceId, token: newToken(), subtotal_aed: round2(amount), discount_aed: 0, taxable_aed: round2(amount), vat_aed: vat, total_aed: round2(amount + vat), prepared_by: staff.id, issued_by: staff.id, approved_by: staff.id, notes: `Credit against ${bundle.invoice.number}: ${description}`, customer_snapshot: bundle.invoice.customer_snapshot, vehicle_snapshot: bundle.invoice.vehicle_snapshot, created_by: staff.id, updated_by: staff.id }).select("id").single();
  if (error || !cn) redirect(`${back}?error=${encodeURIComponent(error?.message ?? "Could not issue the credit note.")}`);
  await admin.from("invoice_lines").insert({ invoice_id: cn.id, position: 0, section: "services", description, quantity: 1, unit_price: round2(amount), amount_aed: round2(amount), vat_aed: vat, total_aed: round2(amount + vat), created_by: staff.id, updated_by: staff.id });
  // A credit note on a job that carries a commission: the owner is flagged (a clawback may apply).
  if (bundle.invoice.job_id) {
    const { data: comm } = await admin.from("quotations").select("id, number, commission_to, commission_aed, commission_status").eq("job_id", bundle.invoice.job_id).eq("is_active", true).not("commission_to", "is", null).gt("commission_aed", 0).limit(5);
    const hot = (comm ?? []).find((c) => c.commission_status !== "declined");
    if (hot) await notifyRoles(["owner"], { type: "commission_approval", title: `Credit note on a job with a commission · ${hot.number}`, body: `${hot.commission_to} has AED ${Number(hot.commission_aed).toLocaleString("en-GB")} commission on this job and a credit note was just issued. Check it on the Commissions page.`, jobId: bundle.invoice.job_id, href: "/commissions" });
  }
  if (bundle.invoice.job_id) await admin.from("job_events").insert({ job_id: bundle.invoice.job_id, event_type: "credit_note", note: `${number} issued by ${staff.display_name} against ${bundle.invoice.number}: AED ${round2(amount + vat).toLocaleString("en-GB", { minimumFractionDigits: 2 })} with VAT (${description})`, created_by: staff.id });
  refresh(bundle.invoice.job_id, invoiceId);
  redirect(`/invoices/${cn.id}?message=${encodeURIComponent(`${number} issued.`)}`);
}

/** Records that the "car is ready" message with the invoice went to the customer. */
async function liveProforma(jobId: string) {
  const { data } = await createAdminClient().from("invoices").select("id, number, total_aed, token, sent_at, expected_payment_method, pay_now_enabled").eq("job_id", jobId).eq("kind", "proforma").eq("status", "issued").eq("is_active", true).is("converted_to", null).is("deposit_for_quotation_id", null).order("issued_at", { ascending: false }).limit(1).maybeSingle();
  return data;
}

/**
 * Before the proforma goes out: how the customer will pay (compulsory), Pay now by Network International, or a
 * pasted payment link. Saved on the proforma; the message is sent in the next step.
 */
export async function prepareProformaSend(jobId: string, opts: { expected: string | null; payNow?: boolean; linkUrl?: string | null }): Promise<{ error?: string; ok?: boolean; payNowError?: string; payNowOn?: boolean }> {
  const staff = await requirePermission("sendApproval");
  const admin = createAdminClient();
  const expected = opts.expected;
  if (!expected || !PAYMENT_METHODS.includes(expected as (typeof PAYMENT_METHODS)[number])) return { error: "Choose how the customer will pay before sending." };
  const pro = await liveProforma(jobId);
  if (!pro) return { error: "There is no proforma on this job yet." };
  let payNowError: string | undefined;
  let payNowOn = false;
  if (opts.linkUrl) {
    const v = validateGatewayUrl(opts.linkUrl, await getSettings());
    if (!v.ok) return { error: v.error };
    const r = await replacePaymentLink(pro.id, opts.linkUrl, { id: staff.id, display_name: staff.display_name });
    if (r.error) return { error: r.error };
    payNowOn = true;
  } else if (opts.payNow) {
    const r = await ensureAutoPayLink(pro.id, { id: staff.id, display_name: staff.display_name }, await getSiteUrl());
    if (r.error) payNowError = r.error;
    else payNowOn = true;
  }
  await admin.from("invoices").update({ expected_payment_method: expected, pay_now_enabled: payNowOn || !!pro.pay_now_enabled, updated_by: staff.id }).eq("id", pro.id);
  refresh(jobId, pro.id);
  return { ok: true, payNowError, payNowOn };
}

/** Records that the "car is ready" message with the proforma went to the customer; accounts are told the first time. */
export async function markReadySent(jobId: string, method: string, opts: { expected?: string | null } = {}): Promise<{ error?: string; ok?: boolean }> {
  const staff = await requirePermission("sendApproval");
  const admin = createAdminClient();
  const pro = await liveProforma(jobId);
  if (!pro) return { error: "There is no proforma on this job yet." };
  const expected = opts.expected ?? pro.expected_payment_method ?? null;
  if (!expected || !PAYMENT_METHODS.includes(expected as (typeof PAYMENT_METHODS)[number])) return { error: "Choose how the customer will pay before sending." };
  const now = new Date().toISOString();
  const first = !pro.sent_at;
  await admin.from("jobs").update({ ready_sent_at: now }).eq("id", jobId);
  await admin.from("invoices").update({ sent_by: staff.id, sent_at: now, expected_payment_method: expected, updated_by: staff.id }).eq("id", pro.id);
  await admin.from("job_events").insert({ job_id: jobId, event_type: "ready_sent", note: `Proforma ${pro.number} and "your car is ready" sent by ${staff.display_name} (${method}); expected ${PAYMENT_METHOD_LABELS[expected] ?? expected}${pro.pay_now_enabled ? ", Pay now on the page" : ""}`, created_by: staff.id });
  if (first) {
    const { data: job } = await admin.from("jobs").select("job_number, customer:customers(full_name, company_name), vehicle:vehicles(kind, has_plate, plate_country, plate_emirate, plate_code, plate_number, vin)").eq("id", jobId).maybeSingle();
    const cust = job?.customer as unknown as { full_name: string; company_name: string | null } | null;
    const who = cust?.company_name ?? (cust?.full_name ?? "").split(" ")[0] ?? "the customer";
    const plate = job?.vehicle ? formatPlate(job.vehicle as unknown as Parameters<typeof formatPlate>[0]) : job?.job_number ?? "";
    await notifyRoles(["accounts"], { type: "proforma_sent", title: `Proforma ${pro.number} sent: ${who}, AED ${Number(pro.total_aed).toLocaleString("en-GB")}, expected ${PAYMENT_METHOD_LABELS[expected] ?? expected}, ${plate}`, body: "Awaiting payment. Record it here when it arrives.", jobId, href: `/jobs/${jobId}/invoice` });
  }
  refresh(jobId);
  return { ok: true };
}

