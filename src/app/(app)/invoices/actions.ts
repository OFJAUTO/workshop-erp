function refresh(jobId: string | null, invoiceId?: string) {
  revalidatePath("/invoices");
  if (invoiceId) revalidatePath(`/invoices/${invoiceId}`);
  if (jobId) {
    revalidatePath(`/jobs/${jobId}`);
    revalidatePath(`/jobs/${jobId}/invoice`);
    revalidatePath(`/jobs/${jobId}/gate-out`);
  }
  revalidatePath("/dashboard");
  revalidatePath("/profit");
}

async function advisorsOf(jobId: string) {
  return advisorsInCharge(jobId);
}
const actorOf = (s: { id: string; display_name: string; role_id: string; is_head_accountant?: boolean }): Actor => ({ id: s.id, display_name: s.display_name, role_id: s.role_id, is_head_accountant: s.is_head_accountant });

/** The advisor marks the car ready to invoice; accounts are told. */
export async function markReadyToInvoice(jobId: string) {
  const staff = await requirePermission("markReadyToInvoice");
  const admin = createAdminClient();
  const { data: job } = await admin.from("jobs").select("id, job_number, status, is_open, ready_to_invoice_at").eq("id", jobId).maybeSingle();
  if (!job || !job.is_open) redirect(`/jobs/${jobId}?error=${encodeURIComponent("This job is closed.")}`);
  if (!["ready", "pending_wash", "pending_qc", "pending_payment"].includes(job.status)) redirect(`/jobs/${jobId}?error=${encodeURIComponent("The car is not ready yet.")}`);
  const settings = await getSettings();
  await admin.from("jobs").update({ ready_to_invoice_at: new Date().toISOString(), ready_to_invoice_by: staff.id }).eq("id", jobId);
  const inv = await ensureProforma(jobId, { id: staff.id, display_name: staff.display_name }, settings);
  refresh(jobId);
  if (!inv) redirect(`/jobs/${jobId}?error=${encodeURIComponent("Nothing to invoice: no approved quotation and no inspection fee.")}`);
  redirect(`/jobs/${jobId}?message=${encodeURIComponent(inv!.kind === "proforma" ? `${inv!.number} is ready. Send it to the customer.` : `${inv!.number} is the tax invoice for this job.`)}`);
}

/**
 * The tax invoice is generated by itself when the proforma is paid in full. This screen's button
 * prepares a missing proforma; only the owner can issue the tax invoice while money is still owed,
 * with a reason that accounts are told.
 */
export async function issueInvoice(jobId: string, formData: FormData) {
  const staff = await requirePermission("issueInvoices");
  const back = `/jobs/${jobId}/invoice`;
  const admin = createAdminClient();
  const settings = await getSettings();
  const reason = blankToNull(formData.get("reason"));
  const { data: job } = await admin.from("jobs").select("id, job_number, status, is_open").eq("id", jobId).maybeSingle();
  if (!job || !job.is_open) redirect(`${back}?error=${encodeURIComponent("This job is closed.")}`);
  const { data: existing } = await admin.from("invoices").select("id, number").eq("job_id", jobId).eq("kind", "tax_invoice").eq("status", "issued").eq("is_active", true).maybeSingle();
  if (existing) redirect(`/invoices/${existing.id}?error=${encodeURIComponent(`${existing.number} is already issued for this job. Corrections are by credit note.`)}`);
  const { data: before } = await admin.from("invoices").select("id").eq("job_id", jobId).eq("kind", "proforma").eq("status", "issued").eq("is_active", true).is("converted_to", null).limit(1);
  const hadProforma = (before ?? []).length > 0;
  const inv = await ensureProforma(jobId, { id: staff.id, display_name: staff.display_name }, settings);
  if (!inv) redirect(`${back}?error=${encodeURIComponent("Nothing to invoice: no approved quotation and no inspection fee.")}`);
  refresh(jobId, inv!.id);
  if (inv!.kind === "tax_invoice") redirect(`/invoices/${inv!.id}?message=${encodeURIComponent(`${inv!.number} issued: paid in full.`)}`);
  if (!hadProforma) redirect(`${back}?message=${encodeURIComponent(`${inv!.number} prepared. The advisor sends it; the tax invoice follows when it is paid in full.`)}`);
  if (staff.role_id !== "owner") redirect(`${back}?error=${encodeURIComponent("The tax invoice is generated by itself when the proforma is paid in full. Only the owner can issue it earlier, with a reason.")}`);
  if (!reason || reason.length < 3) redirect(`${back}?error=${encodeURIComponent("Write the reason for issuing the tax invoice before full payment; accounts are told.")}`);
  const tax = await convertProformaIfPaid(jobId, staff.id, settings, { force: { reason } });
  if (!tax) redirect(`${back}?error=${encodeURIComponent("Could not issue the tax invoice.")}`);
  refresh(jobId, tax!.id);
  redirect(`/invoices/${tax!.id}?message=${encodeURIComponent(`${tax!.number} issued before full payment. Accounts have been told.`)}`);
}

/**
 * A payment: cash, card, link or cheque, against an invoice or as a deposit on the job. One tap, one
 * receipt: the same tap twice records nothing twice; more than the balance waits for the owner.
 */
export async function recordPayment(formData: FormData) {
  const staff = await requirePermission("recordPayments");
  const settings = await getSettings();
  const invoiceId = blankToNull(formData.get("invoice_id"));
  const jobIdIn = blankToNull(formData.get("job_id"));
  const returnTo = blankToNull(formData.get("return_to"));
  const base = invoiceId ? `/invoices/${invoiceId}` : jobIdIn ? `/jobs/${jobIdIn}/invoice` : "/invoices";
  // Back to where the tap happened: the job's invoice page or the invoice's own page, never anywhere else.
  const ownPage = !!returnTo && /^\/(jobs\/[0-9a-f-]{36}\/invoice|invoices\/[0-9a-f-]{36})$/.test(returnTo.split("?")[0]);
  const back = returnTo && ownPage && !returnTo.includes("message=") && !returnTo.includes("error=") ? returnTo : base;
  const sep = back.includes("?") ? "&" : "?";
  const amount = Number(String(formData.get("amount") ?? "").replace(/[^\d.]/g, ""));
  const method = String(formData.get("method") ?? "");
  if (!methodsFor(staff.role_id).includes(method as (typeof PAYMENT_METHODS)[number])) redirect(`${back}${sep}error=${encodeURIComponent("Not allowed: payments are recorded by accounts or the owner only.")}`);
  // A card or transfer payment carries its proof (the card slip, the transfer screenshot) or it is not recorded.
  const proof = formData.get("proof");
  const proofFile = proof instanceof File && proof.size > 0 ? proof : null;
  if ((method === "card" || method === "transfer") && !proofFile) redirect(`${back}${sep}error=${encodeURIComponent(method === "card" ? "Attach a photo of the card slip first." : "Attach the transfer proof (screenshot or photo) first.")}`);
  if (proofFile && proofFile.size > 25 * 1024 * 1024) redirect(`${back}${sep}error=${encodeURIComponent("The proof photo is too large (over 25 MB).")}`);
  const r = await recordPaymentCore(actorOf(staff), {
    invoiceId,
    jobId: jobIdIn,
    method: String(formData.get("method") ?? ""),
    amount,
    reference: blankToNull(formData.get("reference")),
    cheque: { number: blankToNull(formData.get("cheque_number")), bank: blankToNull(formData.get("cheque_bank")), date: blankToNull(formData.get("cheque_date")) },
    notes: blankToNull(formData.get("notes")),
    clientKey: blankToNull(formData.get("client_key")),
  }, settings);
  if (!r.error && r.paymentId && proofFile) {
    const admin = createAdminClient();
    const ext = proofFile.type.includes("png") ? "png" : proofFile.type.includes("webp") ? "webp" : proofFile.type.includes("pdf") ? "pdf" : "jpg";
    const path = `payments/${r.paymentId}.${ext}`;
    const { error: upErr } = await admin.storage.from("job-files").upload(path, Buffer.from(await proofFile.arrayBuffer()), { contentType: proofFile.type || "image/jpeg", upsert: true });
    if (!upErr) await admin.from("payments").update({ proof_path: path, updated_by: staff.id }).eq("id", r.paymentId);
  }
  const jobId = jobIdIn ?? (invoiceId ? (await loadInvoice(invoiceId))?.invoice.job_id ?? null : null);
  // A part payment: the Pay now order (if any) is remade for what is left.
  if (invoiceId && !r.error) {
    const cur = currentPaymentLink(await paymentLinksOf(invoiceId));
    if (cur?.provider === "ngenius" && !cur.paid_at) await ensureAutoPayLink(invoiceId, { id: staff.id, display_name: staff.display_name }, await getSiteUrl());
  }
  refresh(jobId, invoiceId ?? undefined);
  redirect(`${back}${sep}${r.error ? "error" : "message"}=${encodeURIComponent(r.error ?? r.message ?? "Recorded.")}`);
}

/**
 * The advisor heard from the customer that the money was sent (a transfer or a link): the proforma shows
 * "Customer says paid, checking" and accounts are asked to look at the bank. Nothing is released by it.
 */
export async function customerSaysPaid(invoiceId: string, formData: FormData) {
  const staff = await requirePermission("viewInvoices");
  const admin = createAdminClient();
  const bundle = await loadInvoice(invoiceId);
  const returnTo = blankToNull(formData.get("return_to"));
  const back = returnTo && returnTo.startsWith("/") ? returnTo.split("?")[0] : bundle?.invoice.job_id ? `/jobs/${bundle.invoice.job_id}/invoice` : `/invoices/${invoiceId}`;
  if (!bundle) redirect("/invoices");
  const method = blankToNull(formData.get("method"));
  const note = blankToNull(formData.get("note"));
  const now = new Date().toISOString();
  await admin.from("invoices").update({ customer_says_paid_at: now, customer_says_paid_by: staff.id, customer_says_paid_method: method, customer_says_paid_note: note, updated_by: staff.id }).eq("id", invoiceId);
  const { data: job } = bundle!.invoice.job_id ? await admin.from("jobs").select("job_number, vehicle:vehicles(kind, has_plate, plate_country, plate_emirate, plate_code, plate_number, vin)").eq("id", bundle!.invoice.job_id).maybeSingle() : { data: null };
  const plate = job?.vehicle ? formatPlate(job.vehicle as unknown as Parameters<typeof formatPlate>[0]) : bundle!.invoice.number;
  const live = bundle!.payments.filter((p) => p.status === "recorded");
  const due = round2(bundle!.invoice.total_aed - live.filter((p) => p.method !== "cheque" || p.cheque_status === "cleared").reduce((a, p) => a + p.amount_aed, 0));
  if (bundle!.invoice.job_id) await admin.from("job_events").insert({ job_id: bundle!.invoice.job_id, event_type: "payment", note: `Customer says paid (${method ? PAYMENT_METHOD_LABELS[method] ?? method : "method not given"})${note ? `: ${note}` : ""}, noted by ${staff.display_name}. Accounts asked to check.`, created_by: staff.id });
  await notifyRoles(["accounts"], { type: "customer_says_paid", title: `Customer says paid: ${plate}, AED ${due.toLocaleString("en-GB")}`, body: `${bundle!.invoice.number}${method ? ` by ${PAYMENT_METHOD_LABELS[method] ?? method}` : ""}${note ? ` · ${note}` : ""}. Check the bank and record the payment.`, jobId: bundle!.invoice.job_id, href: bundle!.invoice.job_id ? `/jobs/${bundle!.invoice.job_id}/invoice` : `/invoices/${invoiceId}` });
  refresh(bundle!.invoice.job_id, invoiceId);
  redirect(`${back}?message=${encodeURIComponent("Noted: customer says paid. Accounts have been asked to check the bank.")}`);
}

